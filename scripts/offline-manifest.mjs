import {createHash} from 'node:crypto';
import {readFile, readdir, writeFile} from 'node:fs/promises';
import {join, resolve} from 'node:path';

const workerImport = /^importScripts\('\/offline-assets\.js(?:\?v=[a-f0-9]{16})?'\);$/m;
function canonicalWorker(source) {
  if (!workerImport.test(source)) throw new Error('The offline worker must import its generated asset manifest.');
  return source.replace(workerImport, "importScripts('/offline-assets.js');");
}

export async function offlineManifest(root = resolve('dist')) {
  const names = (await readdir(root)).filter(name =>
    /\.(?:html|js|mjs|css|json|png|webp|svg|woff2)$/.test(name) &&
    !['sw.js', 'offline-assets.js', 'deck-workspace.html', 'deck-workspace.mjs'].includes(name));
  for (const name of await readdir(join(root, 'vendor'))) {
    if (name.endsWith('.js')) names.push('vendor/' + name);
  }
  names.sort();
  const hash = createHash('sha256');
  for (const name of names) {
    hash.update(name).update(await readFile(join(root, name)));
  }
  // Exclude the generated import version from its own fingerprint so repeated
  // builds are stable, while changes to the worker's behavior still invalidate it.
  hash.update(canonicalWorker(await readFile(join(root, 'sw.js'), 'utf8')));
  return {version: hash.digest('hex').slice(0, 16), assets: names.map(name => '/' + name)};
}

export async function writeOfflineManifest(root = resolve('dist')) {
  const manifest = await offlineManifest(root);
  const output = '// Generated by npm run check. Cache only public application assets.\n' +
    'self.PITCHVIVA_OFFLINE = ' + JSON.stringify(manifest, null, 2) + ';\n';
  await writeFile(join(root, 'offline-assets.js'), output);
  const worker = canonicalWorker(await readFile(join(root, 'sw.js'), 'utf8'));
  // A release changes the main worker's bytes and the imported script URL. Even
  // an older installed app therefore discovers it without reusing an old manifest.
  await writeFile(join(root, 'sw.js'), worker.replace(workerImport,
    "importScripts('/offline-assets.js?v=" + manifest.version + "');"));
  return manifest;
}
